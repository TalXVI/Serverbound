using System;
using System.Linq;
using System.Reflection;
using HarmonyLib;
using UnityEngine;

namespace Serverbound.Compatibility
{
    internal static class ComfortPortalPatch
    {
        internal const string VendorGuid = "xyz.alcan.comfortcalc";
        private static Func<string, Assembly?>? resolveAssembly;
        private static bool pending;

        internal static void Prepare(Func<string, Assembly?> resolve, bool dedicated)
        {
            resolveAssembly = dedicated ? resolve : null;
            pending = dedicated;
        }

        internal static void Verify()
        {
            if (!pending || resolveAssembly == null) return;
            pending = false;
            Assembly? vendor = resolveAssembly(VendorGuid);
            if (vendor == null)
            {
                CompatibilityInstaller.Info("ComfortPortals: optional mod absent; no takeover needed.");
                return;
            }

            (MethodBase Target, Patch Hook, HarmonyPatchType Kind)? removed = null;
            try
            {
                Guard.Build(typeof(ZNet).Assembly, ExpectedBuilds.Server);
                Guard.Build(vendor, ExpectedBuilds.ComfortTweaks);
                Type group = Guard.Type(vendor, "ComfortTweaks.ComfortTweaks+PlayerUsesPortal");
                MethodInfo target = Guard.Method(typeof(TeleportWorldTrigger), "OnTriggerEnter", typeof(void), typeof(Collider));
                MethodInfo prefix = Guard.Method(group, "Prefix", typeof(void), typeof(TeleportWorldTrigger), typeof(Collider));
                MethodInfo finalizer = Guard.Method(group, "Finalizer", typeof(Exception), typeof(Exception));
                Patch[] before = SimulationPatch.All(target).ToArray();
                Patch[] matches = before.Where(p => p.PatchMethod == prefix).ToArray();
                if (matches.Length != 1 || !matches[0].owner.StartsWith("harmony-auto-", StringComparison.Ordinal)
                    || !Guid.TryParse(matches[0].owner.Substring("harmony-auto-".Length), out _))
                    throw new NotSupportedException("Expected ComfortTweaks' autogenerated Harmony owner and one portal prefix.");
                var saved = SimulationPatch.ExactHook(typeof(TeleportWorldTrigger), target.Name, prefix, matches[0].owner, HarmonyPatchType.Prefix);
                Patch[] finalizers = before.Where(p => p.PatchMethod == finalizer).ToArray();
                if (finalizers.Length != 1 || finalizers[0].owner != saved.Hook.owner
                    || !Harmony.GetPatchInfo(target)!.Finalizers.Contains(finalizers[0]))
                    throw new NotSupportedException("Unexpected ComfortTweaks portal finalizer registration.");

                // Rested checks belong to the casting client. On a headless server null == null
                // admits every nonplayer collider and then dereferences the absent local player.
                removed = saved;
                new Harmony(saved.Hook.owner).Unpatch(target, prefix);
                Patch[] after = SimulationPatch.All(target).ToArray();
                if (after.Length != before.Length - 1 || after.Any(p => p.PatchMethod == prefix)
                    || before.Where(p => p != saved.Hook).Any(old => !after.Any(p => p.PatchMethod == old.PatchMethod
                        && p.owner == old.owner && p.priority == old.priority && p.debug == old.debug
                        && p.before.SequenceEqual(old.before) && p.after.SequenceEqual(old.after))))
                    throw new InvalidOperationException("Portal takeover changed an unrelated registration.");
                CompatibilityInstaller.Info("ComfortPortals: APPLIED; client-local rested checks removed from dedicated portal triggers.");
            }
            catch (Exception error)
            {
                if (removed.HasValue)
                {
                    try { SimulationPatch.Restore(removed.Value); }
                    catch (Exception rollback) { CompatibilityInstaller.Error("ComfortPortals: rollback failed; stop the server. " + rollback); }
                }
                CompatibilityInstaller.Error("ComfortPortals: NOT APPLIED; dedicated nonplayer portal entries can throw. " + error);
            }
        }
    }
}
